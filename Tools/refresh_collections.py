#!/usr/bin/env python3
"""Read-only import from a matching local core/client; never stores credentials."""
import argparse
import collections
import json
import os
from pathlib import Path
import re
import subprocess
import sys
sys.path.insert(0, str(Path(__file__).resolve().parent))
from db2_reader import WDC5

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--config', type=Path, help='Local worldserver config (read only)')
parser.add_argument('--cached', action='store_true', help='Reuse the already imported local names/metadata without SQL')
parser.add_argument('--dbc', type=Path, required=True, help='Matching extracted frFR DB2 directory')
parser.add_argument('--mysql', type=Path, default=ROOT.parent/'mysql/bin/mysql.exe')
args = parser.parse_args()
if not args.cached and not args.config: parser.error('--config is required unless --cached is used')
config = args.config.read_text(encoding='utf-8-sig') if args.config else ''
connection = re.search(r'^WorldDatabaseInfo\s*=\s*"([^"]+)"', config, re.M).group(1).split(';') if config else ['127.0.0.1','3317','','','world']
hotfix = re.search(r'^HotfixDatabaseInfo\s*=\s*"([^"]+)"', config, re.M)
world, hotfix = connection[4], hotfix.group(1).split(';')[4] if hotfix else 'hotfixes'
if not all(re.fullmatch(r'[A-Za-z0-9_]+', name) for name in (world, hotfix)):
    raise SystemExit('Unsupported schema identifier')
env = dict(os.environ, MYSQL_PWD=connection[3])
pending_files = {}

def stage(path, content):
    pending_files[path] = content

def query(sql):
    if args.cached: return []
    proc = subprocess.run([str(args.mysql), '--protocol=tcp', '--host='+connection[0], '--port='+connection[1], '--user='+connection[2], '--default-character-set=utf8mb4', '--batch', '--raw', '--skip-column-names', '--execute='+sql], env=env, capture_output=True, check=True)
    return [line.split('\t') for line in proc.stdout.decode('utf-8').splitlines()]

def s(value):
    return json.dumps(value, ensure_ascii=False)

def unhex(value):
    return bytes.fromhex(value).decode('utf-8') if value and value!='NULL' else ''

def flat_rows(file):
    text = (ROOT/'Data'/file).read_text(encoding='utf-8')
    return [json.loads('['+line.strip()[1:-2]+']') for line in text.splitlines() if line.startswith('  {')]

def write_rows(file, variable, rows):
    def lua(value):
        if isinstance(value, list): return '{'+','.join(map(lua,value))+'}'
        return s(value)
    stage(ROOT/'Data'/file,'-- Generated by Tools/refresh_collections.py from matching local SQL/DB2.\nlocal _, FGM = ...\nFGM.Data.'+variable+' = {\n'+''.join('  '+lua(row)+',\n' for row in rows)+'}\n')

names = {locale:collections.defaultdict(dict) for locale in ('enUS','frFR','esES')}
details = {locale:collections.defaultdict(dict) for locale in names}
if args.cached:
    current = None
    for line in (ROOT/'Data/LocalizedNames.lua').read_text(encoding='utf-8').splitlines():
        header=re.match(r'FGM.Data.(LocalizedNames|LocalizedDetails)\["([^"]+)"\]\["([^"]+)"\] = \{',line)
        if header:
            variable,locale,kind=header.groups();current=(names if variable=='LocalizedNames' else details)[locale][kind]
        else:
            entry=re.match(r'  \[(\d+)\]=(.*),$',line)
            if entry and current is not None: current[int(entry[1])]=json.loads(entry[2])
items = {row[0]:row for row in flat_rows('Items.lua')}
old_items = len(items)
def baseline_count(file, fallback):
    baseline = subprocess.run(['git','-C',str(ROOT),'show','HEAD:Data/'+file],capture_output=True)
    return len(re.findall(rb'^  \{\d+,',baseline.stdout,re.M)) if baseline.returncode==0 else fallback
old_items=baseline_count('Items.lua',old_items)
reference = json.loads((ROOT/'Tools/ReferenceData.json').read_text(encoding='utf-8'))
for row in query(f'SELECT id,HEX(name),quality,itemLevel,requiredLevel,class,subclass,inventoryType,iconFileDataId FROM {world}.armory_item ORDER BY id'):
    item_id = int(row[0]); french = unhex(row[1]); alias = reference.get('items',{}).get(str(item_id),{}).get('1','')
    if french: names['frFR']['items'][item_id] = french
    if alias: names['enUS']['items'][item_id] = alias
    if item_id not in items:
        items[item_id] = [item_id,french or alias,*map(int,row[2:]),alias]
for row in items.values():
    if row[9]: names['enUS']['items'][row[0]] = row[9]
write_rows('Items.lua','Items',[items[i] for i in sorted(items)])

# Preserve existing enriched spell rows; append new locally extracted IDs only.
spell_text=(ROOT/'Data/Spells.lua').read_text(encoding='utf-8')
spell_ids=set(map(int,re.findall(r'^  \{(\d+),',spell_text,re.M)))
old_spells=baseline_count('Spells.lua',len(spell_ids))
spell_names={int(i):unhex(n) for i,n in query(f"SELECT ID,HEX(Name) FROM {world}.forever_armory_source_spell_name WHERE Name<>'' ORDER BY ID")}
spell_icons={int(i):int(n) for i,n in query(f'SELECT SpellID,MAX(SpellIconFileDataID) FROM {world}.forever_armory_source_spell_misc GROUP BY SpellID')}
if args.cached:
    for match in re.finditer(r'^  \{(\d+),("(?:\\.|[^"\\])*"),(\d+),',spell_text,re.M):
        spell_names[int(match[1])]=json.loads(match[2]);spell_icons[int(match[1])]=int(match[3])
extra=[]
for spell_id in sorted(spell_names.keys()-spell_ids):
    extra.append('  {'+f'{spell_id},{s(spell_names[spell_id])},{spell_icons.get(spell_id,0)},0,"other","",0,0,{{}},0'+'},\n')
if extra:
    closing=spell_text.rfind('}')
    stage(ROOT/'Data/Spells.lua',spell_text[:closing]+''.join(extra)+spell_text[closing:])
spell_ids.update(spell_names)
mounts={}
baseline_mounts=subprocess.run(['git','-C',str(ROOT),'show','HEAD:Data/Mounts.lua'],capture_output=True)
factions={int(m[1]):int(m[2]) for m in re.finditer(r'^  \{(\d+),"(?:\\.|[^"\\])*",(\d+),',baseline_mounts.stdout.decode('utf-8'),re.M)}
for mount_id,fields in WDC5(args.dbc/'Mount.db2',0xE4B71B79).rows([4,7,8]):
    spell_id=fields[7]
    if spell_id<=0: continue
    # Mount.db2 itself is authoritative for SourceSpellID. Preserve newly
    # referenced IDs even if the extracted SpellName snapshot has no name yet.
    mounts[spell_id]=[spell_id,spell_names.get(spell_id,''),factions.get(spell_id,0),spell_icons.get(spell_id,132261),fields[4],fields[8],0 if spell_id in spell_ids else 1]
    if spell_names.get(spell_id): names['frFR']['mounts'][spell_id]=spell_names[spell_id]
old_mounts=baseline_count('Mounts.lua',len(flat_rows('Mounts.lua')))
write_rows('Mounts.lua','Mounts',[mounts[i] for i in sorted(mounts)])

# Complete client sets, not just labels present in a reference addon.
class_ids=[8,5,9,4,11,3,7,2,1]
tiers={i:('t1',c) for i,c in zip(range(201,210),class_ids)}
tiers.update({i:('t2',c) for i,c in zip(range(210,219),class_ids)})
tiers.update({i:('t3',c) for i,c in [(521,11),(523,1),(524,4),(525,5),(526,8),(527,7),(528,2),(529,9),(530,3)]})
tier_english=['Arcanist Regalia','Vestments of Prophecy','Felheart Raiment','Nightslayer Armor','Cenarion Raiment','Giantstalker Armor','The Earthfury','Lawbringer Armor','Battlegear of Might','Netherwind Regalia','Vestments of Transcendence','Nemesis Raiment','Bloodfang Armor','Stormrage Raiment','Dragonstalker Armor','The Ten Storms','Judgement Armor','Battlegear of Wrath']
english_tiers=dict(zip(range(201,219),tier_english))
sets=[]; skipped={}
for set_id,fields in WDC5(args.dbc/'ItemSet.db2',0xF79068A4).rows([0]+[(4,i) for i in range(17)],string_fields=[0]):
    members=sorted({v for k,v in fields.items() if isinstance(k,tuple) and v})
    missing=[i for i in members if i not in items]
    if not members: continue
    if missing and set_id not in tiers: continue
    if missing: skipped[set_id]=missing
    ref=reference.get('sets',{}).get(str(set_id),{})
    label=ref.get('name') or english_tiers.get(set_id) or ''
    category, class_id=tiers.get(set_id,('other',0))
    # Client-defined remastered tier variants: classify by the verified name,
    # never replace legacy IDs with guessed aliases.
    if category=='other' and set_id>1000:
        if re.search(r'Arcanist|Prophecy|Felheart|Nightslayer|Cenarion|Giantstalker|Earthfury|Lawbringer|Might',label,re.I): category='t1'
        elif re.search(r'Netherwind|Transcendence|Nemesis|Bloodfang|Stormrage|Dragonstalker|Ten Storms|Judgement|Wrath',label,re.I): category='t2'
    mask=2**(class_id-1) if class_id else ref.get('classes',-1)
    sets.append([set_id,label,mask,members,next((items[i][8] for i in members if i in items and items[i][8]),0),category,'',missing])
    if label: names['enUS']['bis'][set_id]=label
    if fields[0]: names['frFR']['bis'][set_id]=fields[0]
write_rows('ItemSets.lua','ItemSets',sets)

known={
 'items':set(items), 'spells':spell_ids, 'mounts':set(mounts), 'bis':{r[0] for r in sets},
 'quests':{r[0] for r in flat_rows('Quests.lua')}, 'npcs':{r[0] for r in flat_rows('Creatures.lua')},
 'gameobjects':{r[0] for r in flat_rows('GameObjects.lua')}, 'achievements':{r[0] for r in flat_rows('Achievements.lua')},
}
queries=[
 ('quests',f"SELECT ID,locale,HEX(LogTitle),'' FROM {world}.quest_template_locale WHERE locale IN ('frFR','esES') AND LogTitle<>''"),
 ('npcs',f"SELECT entry,locale,HEX(Name),HEX(COALESCE(Title,'')) FROM {world}.creature_template_locale WHERE locale IN ('frFR','esES') AND Name<>''"),
 ('gameobjects',f"SELECT entry,locale,HEX(name),'' FROM {world}.gameobject_template_locale WHERE locale IN ('frFR','esES') AND name<>''"),
 ('spells',f"SELECT ID,locale,HEX(Name_lang),'' FROM {hotfix}.spell_name_locale WHERE locale IN ('frFR','esES') AND Name_lang<>'' ORDER BY VerifiedBuild"),
 ('items',f"SELECT ID,locale,HEX(Display_lang),'' FROM {hotfix}.item_sparse_locale WHERE locale IN ('frFR','esES') AND Display_lang<>'' ORDER BY VerifiedBuild"),
 ('achievements',f"SELECT ID,locale,HEX(Title_lang),HEX(COALESCE(Description_lang,'')) FROM {hotfix}.achievement_locale WHERE locale IN ('frFR','esES') AND Title_lang<>'' ORDER BY VerifiedBuild"),
 ('spells',f"SELECT ID,'enUS',HEX(Name),'' FROM {hotfix}.spell_name WHERE Name<>'' ORDER BY VerifiedBuild"),
 ('items',f"SELECT ID,'enUS',HEX(Display),'' FROM {hotfix}.item_sparse WHERE Display<>'' ORDER BY VerifiedBuild"),
]
for kind,sql in queries:
    for identifier,locale,title,description in query(sql):
        identifier=int(identifier)
        if identifier not in known[kind]: continue
        names[locale][kind][identifier]=unhex(title)
        if description: details[locale][kind][identifier]=unhex(description)
for locale in names:
    for spell_id in mounts:
        if spell_id in names[locale]['spells']: names[locale]['mounts'][spell_id]=names[locale]['spells'][spell_id]

def write_maps(file, groups):
    lines=['-- Generated offline from matching local SQL/DB2; no credentials or config paths.','local _, FGM = ...']
    for variable,data in groups:
        lines.append('FGM.Data.'+variable+' = FGM.Data.'+variable+' or {}')
        for locale,kinds in data.items():
            prefix='FGM.Data.'+variable+'['+s(locale)+']'
            lines.append(prefix+' = '+prefix+' or {}')
            for kind,entries in sorted(kinds.items()):
                lines.append(prefix+'['+s(kind)+'] = {')
                lines.extend('  ['+str(i)+']='+s(value)+',' for i,value in sorted(entries.items()) if value)
                lines.append('}')
    stage(ROOT/'Data'/file,'\n'.join(lines)+'\n')
write_maps('LocalizedNames.lua',[('LocalizedNames',names),('LocalizedDetails',details)])
translations=json.loads((ROOT/'Tools/SkillTranslations.json').read_text(encoding='utf-8'))
skill_names={locale:collections.defaultdict(dict) for locale in ('enUS','esES')}
skills=flat_rows('Skills.lua')
for skill in skills:
    pair=translations[str(skill[0])]
    for locale,value in zip(('enUS','esES'),pair):
        skill_names[locale]['skills'][skill[0]]=value
        if skill[2]==10: skill_names[locale]['languages'][skill[0]]=value
write_maps('SkillNames.lua',[('LocalizedNames',skill_names)])
report={'items':len(items),'newItems':len(items)-old_items,'spells':len(spell_ids),'newSpells':len(spell_ids)-old_spells,'mounts':len(mounts),'mountChange':len(mounts)-old_mounts,'mountNamesPending':sorted(i for i,r in mounts.items() if r[6]),'sets':len(sets),'tiers':{key:sum(row[5]==key for row in sets) for key in ('t1','t2','t3')},'missingTierMembers':skipped,'offlineNames':{locale:{kind:len(entries) for kind,entries in kinds.items() if entries} for locale,kinds in names.items()}}
stage(ROOT/'docs/LOCALE_COVERAGE.json',json.dumps(report,ensure_ascii=False,indent=2)+'\n')

# Phase-6 source candidates are not an optimized single loadout. Only exact,
# unique name-to-ID matches in this client's item catalog can be granted.
references=json.loads((ROOT/'Tools/BiSReferences.json').read_text(encoding='utf-8'))
index=collections.defaultdict(set)
for identifier,label in names['enUS']['items'].items():
    if identifier in items: index[label.casefold()].add(identifier)
profiles=[];profile_report=[]
for reference in references:
    class_id=reference['classID'];members=[];unresolved=[]
    for label in reference['itemNames']:
        candidates=index[label.casefold()]
        classic={i for i in candidates if i<100000}
        candidates=classic or candidates
        if len(candidates)==1: members.append(next(iter(candidates)))
        else: unresolved.append(label)
    members=sorted(set(members))
    if not members: continue
    profiles.append([900000+class_id,'',2**(class_id-1),members,items[members[0]][8],'bis',reference['source'],[],class_id,reference['role'],len(unresolved)])
    profile_report.append({'classID':class_id,'source':reference['source'],'availableIDs':members,'unresolvedSourceNames':unresolved,'scope':'Phase 6 source candidates, including alternatives; not a complete optimized loadout'})
def lua_value(value):
    return '{'+','.join(map(lua_value,value))+'}' if isinstance(value,list) else s(value)
stage(ROOT/'Data/BiS.lua','-- Generated from Tools/BiSReferences.json; client-validated source candidates only.\nlocal _, FGM = ...\nFGM.Data.BiS = {profiles={\n'+''.join('  '+lua_value(row)+',\n' for row in profiles)+'}}\nfor _,row in ipairs(FGM.Data.BiS.profiles) do FGM.Data.ItemSets[#FGM.Data.ItemSets+1]=row end\n')
stage(ROOT/'docs/BIS_COVERAGE.json',json.dumps(profile_report,ensure_ascii=False,indent=2)+'\n')
# Do not replace any generated dataset until every query and check completed.
for path,content in pending_files.items():
    path.write_text(content,encoding='utf-8',newline='\n')
print(json.dumps(report,ensure_ascii=False))
print('Phase-6 candidate profiles: '+str(len(profiles)))
